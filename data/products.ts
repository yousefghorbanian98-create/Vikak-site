export const roasters = Array.from(new Set(products.map(p => p.roaster))).sort((a, b) => a.localeCompare(b, 'fa'));

export const origins = Array.from(new Set(products.map(p => p.originFa)));

export function lowestKgPrice(product: Product): number {
  const values = product.variants
    .map(v => v.kgPrice ?? Math.round((v.price / v.grams) * 1000))
    .filter(v => Number.isFinite(v));
  return values.length ? Math.min(...values) : 0;
}

export function startingPrice(product: Product): { price: number; grams: number } {
  const cheapest = [...product.variants].sort((a, b) => a.price - b.price)[0];
  return { price: cheapest.price, grams: cheapest.grams };
}
